#!/bin/sh
# Writes vpsmon-install.sh: one POSIX sh file that installs vpsmon and its sample timer with nothing to download.
# It holds server/vpsmon and both systemd units as heredocs, and server/install-root.sh as the part that runs as root.
#
# Usage: scripts/make-installer.sh <out-file>
set -eu

out=${1:?usage: scripts/make-installer.sh <out-file>}
repo=$(cd "$(dirname "$0")/.." && pwd)
server=$repo/server
version=$(cat "$repo/VERSION")

grep -qx "VERSION = \"$version\"" "$server/vpsmon" || {
  echo "make-installer: server/vpsmon does not say VERSION = \"$version\" like VERSION does" >&2
  exit 1
}
for file in vpsmon systemd/vpsmon-sample.service systemd/vpsmon-sample.timer install-root.sh; do
  if grep -q '^VPSMON_[A-Z]*_EOF$' "$server/$file"; then
    echo "make-installer: server/$file holds a line that would end a heredoc" >&2
    exit 1
  fi
  if [ -n "$(tail -c 1 "$server/$file")" ]; then
    echo "make-installer: server/$file does not end with a newline" >&2
    exit 1
  fi
done

# embed <function> <delimiter> <file>: a function that prints the file.
embed() {
  printf '%s() {\n  cat <<'"'"'%s'"'"'\n' "$1" "$2"
  cat "$3"
  printf '%s\n}\n\n' "$2"
}

tmp=$(mktemp "$out.XXXXXX")
trap 'rm -f "$tmp"' EXIT
{
  cat <<EOF
#!/bin/sh
# vpsmon $version installer, generated by scripts/make-installer.sh: edit the sources in server/, not this file.
#
# Usage: vpsmon-install.sh [--user <name>] [--watch <unit,unit>] [--uninstall]
#    or: curl -fsSL <release url>/vpsmon-install.sh | sudo sh -s -- --user <name>
#
# As root it installs /usr/local/bin/vpsmon and its 5-minute sample timer, and with --user lets that user run vpsmon
# through sudo without a password. As another user it runs itself through sudo -n with --user <that user>. It prints
# one JSON line. docs/contract.md, section Install, is the contract.

# The root half, written to a temp file and run from there: read from stdin (sh -s), this file cannot run itself again.
payload() {
  cat <<'VPSMON_PAYLOAD_EOF'
#!/bin/sh
VPSMON_VERSION=$version
EOF
  embed vpsmon_script VPSMON_SCRIPT_EOF "$server/vpsmon"
  embed vpsmon_service VPSMON_SERVICE_EOF "$server/systemd/vpsmon-sample.service"
  embed vpsmon_timer VPSMON_TIMER_EOF "$server/systemd/vpsmon-sample.timer"
  cat "$server/install-root.sh"
  cat <<'EOF'
VPSMON_PAYLOAD_EOF
}

main() {
  me=$(id -un)
  me_json=$(printf '%s' "$me" | sed 's/\\/\\\\/g; s/"/\\"/g')
  payload_file=$(mktemp "${TMPDIR:-/tmp}/vpsmon-install.XXXXXX")
  trap 'rm -f "$payload_file"' EXIT
  payload >"$payload_file"
  if [ "$(id -u)" -eq 0 ]; then
    sh "$payload_file" "$@" </dev/null
    return
  fi
  if ! command -v sudo >/dev/null 2>&1; then
    printf '{"ok":false,"error":"sudo-missing","user":"%s"}\n' "$me_json"
    return 1
  fi
  if ! sudo -n true </dev/null >/dev/null 2>&1; then
    printf '{"ok":false,"error":"sudo-password","user":"%s"}\n' "$me_json"
    return 1
  fi
  sudo -n sh "$payload_file" --user "$me" "$@" </dev/null
}

main "$@"
EOF
} >"$tmp"
sh -n "$tmp"
chmod 0755 "$tmp"
mv -f "$tmp" "$out"
trap - EXIT
